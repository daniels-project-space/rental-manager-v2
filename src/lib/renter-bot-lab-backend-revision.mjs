import { createHash } from "node:crypto";
import { existsSync, readFileSync, readdirSync, statSync, watch, writeFileSync } from "node:fs";
import { join } from "node:path";

const revisionPath = "convex/lib/renter_bot_lab_build_revision.ts";
const roots = ["convex"];
const rootConfig = ["package.json", "pnpm-lock.yaml", "convex.config.ts"];

/** Hash the exact local Convex source and runtime dependency inputs, excluding this generated stamp. */
export function renterBotLabBackendSourceFingerprint(root = process.cwd()) {
  try {
    const files = [];
    const visit = (relative) => {
      const absolute = join(root, relative);
      if (!existsSync(absolute)) return;
      const stat = statSync(absolute);
      if (stat.isDirectory()) {
        for (const child of readdirSync(absolute).sort()) visit(join(relative, child));
      } else if (stat.isFile() && relative !== revisionPath &&
        !relative.split(/[\\/]/).includes("__tests__") &&
        !/\.(?:test|spec)\.[cm]?[jt]sx?$/i.test(relative) &&
        !/\.d\.ts$/i.test(relative)) {
        files.push(relative);
      }
    };
    for (const path of roots) visit(path);
    for (const path of rootConfig) visit(path);
    if (!files.length) return null;
    const hash = createHash("sha256");
    for (const file of files.sort()) {
      hash.update(file).update("\0").update(readFileSync(join(root, file))).update("\0");
    }
    return hash.digest("hex");
  } catch {
    return null;
  }
}

/** Write the source fingerprint into the bundle so Convex reports the version it actually loaded. */
export function syncRenterBotLabBackendRevision(root = process.cwd()) {
  const fingerprint = renterBotLabBackendSourceFingerprint(root);
  if (!fingerprint) throw new Error("Cannot fingerprint the local Lab backend source");
  const file = join(root, revisionPath);
  const source = `// Generated by scripts/renter-bot-lab-local.mjs; do not edit.\nexport const RENTER_BOT_LAB_BACKEND_SOURCE_REVISION = ${JSON.stringify(fingerprint)};\n`;
  if (!existsSync(file) || readFileSync(file, "utf8") !== source) writeFileSync(file, source, { mode: 0o600 });
  return fingerprint;
}

/** Keep the generated backend revision synchronized while the isolated local Lab is running. */
export function watchRenterBotLabBackendRevision(root = process.cwd(), onRevision = () => {}) {
  let fingerprint = syncRenterBotLabBackendRevision(root);
  let timer;
  const refresh = () => {
    clearTimeout(timer);
    timer = setTimeout(() => {
      try {
        const next = syncRenterBotLabBackendRevision(root);
        if (next !== fingerprint) {
          fingerprint = next;
          onRevision(next);
        }
      } catch (error) {
        onRevision(null, error);
      }
    }, 180);
  };
  const watchers = [
    watch(join(root, "convex"), { recursive: true }, refresh),
    watch(root, refresh),
  ];
  return () => {
    clearTimeout(timer);
    for (const watcher of watchers) watcher.close();
  };
}
