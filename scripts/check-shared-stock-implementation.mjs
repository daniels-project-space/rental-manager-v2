import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";
import ts from "typescript";

const root = process.cwd();
const generated = "convex/lib/shared_stock_implementation.ts";
const config = ts.readConfigFile(path.join(root, "tsconfig.json"), ts.sys.readFile);
if (config.error) throw Error("Cannot read stock dependency configuration");
const options = ts.parseJsonConfigFileContent(config.config, ts.sys, root).options;
const pending = ["convex/lib/shared_stock_cache.ts", "convex/lib/stock_listing_writes.ts", "convex/lib/stock_input_writes.ts", "convex/lib/reservation_revenue.ts", "convex/stock_input_cache_admin.ts"];
const files = new Map(), visited = new Set(), envKeys = new Set();
while (pending.length) {
  const relative = pending.pop();
  if (relative === generated || visited.has(relative)) continue;
  visited.add(relative);
  const filename = path.join(root, relative), source = fs.readFileSync(filename, "utf8");
  files.set(relative, source);
  const ast = ts.createSourceFile(filename, source, ts.ScriptTarget.Latest, true);
  function dependency(specifier, opaque = false) {
    if (specifier.startsWith(".") && !path.resolve(path.dirname(filename), specifier).startsWith(root + path.sep)) throw Error("Stock dependency escapes project");
    const resolved = ts.resolveModuleName(specifier, filename, options, ts.sys).resolvedModule;
    if (!resolved) throw Error(`Unresolved stock dependency: ${relative}: ${specifier}`);
    let name = resolved.resolvedFileName;
    if (name.includes(`${path.sep}node_modules${path.sep}`)) return;
    if (name.endsWith(".d.ts") && fs.existsSync(name.slice(0, -5) + ".js")) name = name.slice(0, -5) + ".js";
    if (!name.startsWith(root + path.sep)) throw Error("Stock dependency escapes project");
    const target = path.relative(root, name).split(path.sep).join("/");
    if (opaque) files.set(target, fs.readFileSync(name, "utf8"));
    else pending.push(target);
  }
  function visit(node) {
    if (ts.isImportDeclaration(node) && !node.importClause?.isTypeOnly) {
      const bindings = node.importClause?.namedBindings;
      const typesOnly = !node.importClause?.name && bindings && ts.isNamedImports(bindings) && bindings.elements.every(element => element.isTypeOnly);
      // These exact imports are QA entrypoints, not projection builders. Keep
      // their wrappers versioned without pulling the unrelated inbox graph in.
      const qaNames = new Set(["__service_getReplyQueue", "__service_getThreadById", "__service_sharedStockForStorefront"]);
      const qaImport = relative === "convex/stock_input_cache_admin.ts" && ["./items", "./replyInbox"].includes(node.moduleSpecifier.text) &&
        bindings && ts.isNamedImports(bindings) && bindings.elements.every(element => qaNames.has((element.propertyName ?? element.name).text));
      if (!typesOnly) dependency(node.moduleSpecifier.text, !!qaImport);
    }
    if (ts.isExportDeclaration(node) && !node.isTypeOnly && node.moduleSpecifier) dependency(node.moduleSpecifier.text);
    if (ts.isCallExpression(node) && (node.expression.kind === ts.SyntaxKind.ImportKeyword || ts.isIdentifier(node.expression) && node.expression.text === "require")) {
      if (!ts.isStringLiteral(node.arguments[0])) throw Error(`Dynamic stock dependency requires an explicit import: ${relative}`);
      dependency(node.arguments[0].text);
    }
    if (ts.isPropertyAccessExpression(node) && ts.isPropertyAccessExpression(node.expression) && node.expression.getText(ast) === "process.env") envKeys.add(node.name.text);
    if (ts.isElementAccessExpression(node) && node.expression.getText(ast) === "process.env") {
      if (relative === "convex/lib/shared_stock_version.ts" && node.argumentExpression.getText(ast) === "key") return;
      if (!ts.isStringLiteral(node.argumentExpression)) throw Error(`Dynamic stock environment key requires explicit configuration: ${relative}`);
      envKeys.add(node.argumentExpression.text);
    }
    ts.forEachChild(node, visit);
  }
  visit(ast);
}
files.set("pnpm-lock.yaml", fs.readFileSync(path.join(root, "pnpm-lock.yaml"), "utf8"));
files.set("scripts/check-shared-stock-implementation.mjs", fs.readFileSync(import.meta.filename, "utf8"));
const digest = crypto.createHash("sha256").update(JSON.stringify([...files].sort(([a], [b]) => a.localeCompare(b)))).digest("hex");
const contents = `// Generated by scripts/check-shared-stock-implementation.mjs --write.\nexport const SHARED_STOCK_CODE = ${JSON.stringify(digest)} as const;\nexport const SHARED_STOCK_ENV_KEYS = ${JSON.stringify([...envKeys].sort())} as const;\n`;
if (process.argv.includes("--write")) fs.writeFileSync(path.join(root, generated), contents);
else if (!fs.existsSync(path.join(root, generated)) || fs.readFileSync(path.join(root, generated), "utf8") !== contents) {
  throw Error("Stock implementation changed; run node scripts/check-shared-stock-implementation.mjs --write and commit the generated version.");
}
console.log(`Stock implementation verified: ${files.size} runtime inputs, ${digest}`);
